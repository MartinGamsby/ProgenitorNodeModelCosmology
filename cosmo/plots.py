"""
Shared Plotting Module — WS2 (Graphs From Scripts)

Every workstream emits its figures through this module so the entire project
uses a uniform style, dpi, path convention and footer stamp.

Output convention
-----------------
  results/figures/<workstream>/<name>.png
  (git-ignored generated artifact; regenerated by scripts; never hand-edited)

Helper
------
  figure_path(workstream, name) -> str
      Ensures the directory exists and returns the absolute path.

Figure functions (F1-F9 of the enumerated set)
-----------------------------------------------
  F1/F2/F3  plot_ms_heatmap(df, metric_col, workstream, name, **kw)
  F4         plot_growth_map(df, workstream, name, **kw)
  F5         plot_eds_overlay(a_sim, t_Gyr, t_start_Gyr, workstream, name, **kw)
  F6         plot_mu_z_panel(sim_dist, results, sim_params, workstream, name, **kw)
  F7         plot_shear_vs_lever(lever_values, shear_values, lever_label,
                                 workstream, name, **kw)
  F8         plot_dipole_vs_lever(lever_values, dipole_values, lever_label,
                                  workstream, name, **kw)
  F9         plot_runaway_boundary(df, workstream, name, **kw)

All functions return the path of the saved PNG.

WS1 caller contract (for the sweep tool / --plots-only mode)
-------------------------------------------------------------
  import pandas as pd
  from cosmo.plots import (figure_path, plot_ms_heatmap, plot_growth_map,
                            plot_runaway_boundary)

  df = pd.read_csv("results/sweep_results_pantheon.csv")
  plot_ms_heatmap(df, "chi2_dof",   "ws1", "ms_chi2_heatmap_vs_pantheon")
  plot_ms_heatmap(df, "chi2_lcdm",  "ws1", "ms_chi2_heatmap_vs_lcdm")
  plot_ms_heatmap(df, "chi2_eds",   "ws1", "ms_chi2_heatmap_vs_eds")
  plot_growth_map(df,               "ws1", "growth_map")
  plot_runaway_boundary(df,         "ws1", "runaway_boundary")

F5 caller contract (for the standalone EdS validation figure)
--------------------------------------------------------------
  from cosmo.plots import plot_eds_overlay
  plot_eds_overlay(a_sim, t_Gyr, t_start_Gyr=2.9,
                   workstream="ws2", name="eds_overlay_M0")

F6 caller contract (for the per-config mu(z)+residual panel)
-------------------------------------------------------------
  from cosmo.plots import plot_mu_z_panel
  plot_mu_z_panel(sim_dist, results, sim_params,
                  workstream="ws2", name=f"mu_z_panel_M{M}_S{S}")
  where sim_dist  = cosmo.sim_distance.sim_to_distance_modulus(...)
        results   = dict keyed by model name (same as hubble_diagram_nbody.run())

F7/F8 caller contract (for anisotropy_report.py)
-------------------------------------------------
  from cosmo.plots import plot_shear_vs_lever, plot_dipole_vs_lever
  plot_shear_vs_lever(amplitudes, shear_values, "node_mass_amplitude",
                      "ws2", "shear_vs_nma")
  plot_dipole_vs_lever(amplitudes, dipole_values, "node_mass_amplitude",
                       "ws2", "dipole_vs_nma")
"""

