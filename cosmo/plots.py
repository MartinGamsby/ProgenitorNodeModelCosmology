def plot_growth_map(
    df,
    workstream: str,
    name: str,
    *,
    growth_col: str = "growth_factor",
    anchor_col: Optional[str] = "anchor_ok",
    title: str = "Growth-factor map over (M, S)",
    target_growth: Optional[float] = None,
) -> str:
    """Plot the realized growth factor a(today)/a(t_start) over the (M, S) grid.

    Cells that fail the growth anchor (``anchor_ok == False``) are cross-hatched
    to visually distinguish bound vs runaway configs.

    Args:
        df:            Sweep results DataFrame.
        workstream:    Sub-directory.
        name:          PNG filename stem.
        growth_col:    Column name for the growth factor (default ``"growth_factor"``).
        anchor_col:    Column name for the boolean anchor flag (``None`` to skip).
        title:         Figure title.
        target_growth: Reference line value for the physical growth anchor.
                       If None the colorbar range auto-scales.

    Returns:
        Path to the saved PNG.
    """
    import pandas as _pd

    df = _pd.DataFrame(df)
    cols_needed = {"M_factor", "S_gpc", growth_col}
    missing = cols_needed - set(df.columns)
    if missing:
        raise ValueError(
            f"plot_growth_map: missing columns {sorted(missing)}."
        )

    pivot = (
        df[["M_factor", "S_gpc", growth_col]]
        .astype({growth_col: float})
        .groupby(["M_factor", "S_gpc"])[growth_col]
        .mean()
        .reset_index()
        .pivot(index="S_gpc", columns="M_factor", values=growth_col)
    )

    M_vals = pivot.columns.values.astype(float)
    S_vals = pivot.index.values.astype(float)
    Z = pivot.values

    fig, ax = plt.subplots(figsize=(9, 6))

    img = ax.pcolormesh(
        M_vals, S_vals, Z,
        cmap="RdYlGn", shading="nearest",
    )
    cbar = fig.colorbar(img, ax=ax)
    cbar.set_label("Growth factor a(today)/a(t_start)", fontsize=11)

    if target_growth is not None:
        cbar.ax.axhline(target_growth, color="blue", lw=1.5, ls="--")
        cbar.ax.annotate(
            f"target={target_growth:.2f}",
            xy=(1.05, target_growth),
            xycoords=("axes fraction", "data"),
            fontsize=7, color="blue",
        )

    # Cross-hatch cells that failed the anchor (runaway)
    if anchor_col is not None and anchor_col in df.columns:
        # Build a bool pivot (False = runaway = hatch)
        anchor_pivot = (
            df[["M_factor", "S_gpc", anchor_col]]
            .copy()
        )
        anchor_pivot["anchor_bool"] = anchor_pivot[anchor_col].map(
            lambda v: (str(v).strip().lower() not in ("false", "0", "no"))
        )
        anc = (
            anchor_pivot.groupby(["M_factor", "S_gpc"])["anchor_bool"]
            .min()
            .reset_index()
            .pivot(index="S_gpc", columns="M_factor", values="anchor_bool")
        )
        # Reindex to match pivot grid
        anc = anc.reindex(index=pivot.index, columns=pivot.columns)
        runaway = ~anc.values.astype(bool)
        for i in range(len(S_vals)):
            for j in range(len(M_vals)):
                if runaway[i, j]:
                    ax.add_patch(plt.Rectangle(
                        (M_vals[j] - 0.4, S_vals[i] - 0.4), 0.8, 0.8,
                        fill=False, hatch="///", edgecolor="red", lw=0.5, zorder=5,
                    ))

    ax.set_xlabel("M (node mass factor)", fontsize=12)
    ax.set_ylabel("S (node separation, Gpc)", fontsize=12)
    ax.set_title(title, fontsize=13)
    ax.set_xscale("log") if np.ptp(np.log10(M_vals[M_vals > 0])) > 1.5 else None

    _footer(ax, f"col={growth_col}")
    fig.tight_layout()
    out = figure_path(workstream, name)
    fig.savefig(out, dpi=_DPI, bbox_inches=_BBOX)
    plt.close(fig)
    return out


