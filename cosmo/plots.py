# F5 — M=0 == EdS overlay
# ---------------------------------------------------------------------------

def plot_eds_overlay(
    a_sim: np.ndarray,
    t_Gyr: np.ndarray,
    t_start_Gyr: float,
    workstream: str,
    name: str,
    *,
    title: str = "M=0 sim vs analytic EdS and ΛCDM",
    z_grid: Optional[np.ndarray] = None,
) -> str:
    """Plot the M=0 from-sim mu(z) alongside the analytic EdS and ΛCDM curves.

    This is the visual proof of PF1: with M=0 the sim reproduces EdS BY
    CONSTRUCTION, so the orange sim curve should sit ON the green EdS null
    and ~10x farther from the blue ΛCDM curve.

    Args:
        a_sim:        Scale-factor array from the simulation (a[0]=1 at t_start).
        t_Gyr:        Relative time array starting at 0, in Gyr (same length as a_sim).
        t_start_Gyr:  Absolute start time in Gyr (e.g. 2.9).
        workstream:   Sub-directory.
        name:         PNG filename stem.
        title:        Figure title.
        z_grid:       Optional redshift grid for analytic curves. Defaults to
                      linspace from sim z_max down to 0.01.

    Returns:
        Path to the saved PNG.
    """
    from .sim_distance import sim_to_distance_modulus
    from .distances import model_distance_modulus

    a_sim = np.asarray(a_sim, dtype=float)
    t_Gyr = np.asarray(t_Gyr, dtype=float)

    # Build a dense z grid spanning the sim's coverage
    if z_grid is None:
        t_abs = t_start_Gyr + t_Gyr
        t_today = 13.8
        a_norm = a_sim / a_sim[-1]
        z_snap = 1.0 / a_norm - 1.0
        z_max_sim = float(np.nanmax(z_snap[z_snap > 0.0]))
        z_grid = np.linspace(0.01, min(z_max_sim * 0.98, 2.3), 400)

    # --- from-sim mu(z) ---
    sd = sim_to_distance_modulus(z_grid, a_sim, t_Gyr, t_start_Gyr=t_start_Gyr)
    z_in = sd["z"]
    mu_sim_raw = sd["mu"]

    # --- analytic EdS and ΛCDM ---
    mu_eds  = model_distance_modulus(z_in, "einstein_de_sitter")
    mu_lcdm = model_distance_modulus(z_in, "lcdm")

    # Offset-marginalize each (using the sim offset)
    def _offset(mu_model, mu_obs):
        """Weighted mean offset — here we use uniform weights for simplicity
        since we only care about visual alignment."""
        return float(np.mean(mu_obs - mu_model))

    # Reference shift: align sim to EdS (they should be nearly identical)
    delta_sim  = _offset(mu_sim_raw,  mu_eds)
    delta_lcdm = _offset(mu_lcdm,     mu_eds)

    mu_sim_shifted  = mu_sim_raw  + delta_sim
    mu_lcdm_shifted = mu_lcdm    + delta_lcdm
    # EdS is the zero reference (no shift)

    fig, axes = plt.subplots(2, 1, figsize=(9, 8),
                             gridspec_kw={"height_ratios": [3, 1], "hspace": 0.08},
                             sharex=True)
    ax_top, ax_res = axes

    ax_top.plot(z_in, mu_sim_shifted, color=_MODEL_COLORS["external_node_nbody"],
                lw=2.5, label="M=0 N-body sim (should = EdS)")
    ax_top.plot(z_in, mu_eds, color=_MODEL_COLORS["einstein_de_sitter"],
                lw=2.0, ls="-.", label="Analytic EdS / matter-only (Ωm=1)")
    ax_top.plot(z_in, mu_lcdm_shifted, color=_MODEL_COLORS["lcdm"],
                lw=2.0, ls="--", label="Analytic ΛCDM (Ωm=0.3, ΩΛ=0.7)")

    ax_top.set_xscale("log")
    ax_top.set_ylabel("Distance modulus μ [mag]", fontsize=12)
    ax_top.set_title(title, fontsize=13)
    ax_top.legend(fontsize=9, loc="upper left")
    ax_top.grid(True, alpha=0.3, which="both")
    plt.setp(ax_top.get_xticklabels(), visible=False)

    # Residual panel: sim - EdS
    residual = mu_sim_shifted - mu_eds
    residual_lcdm = mu_lcdm_shifted - mu_eds
    ax_res.axhline(0.0, color=_MODEL_COLORS["einstein_de_sitter"], lw=1.5, ls="-.",
                   label="EdS (reference, 0)")
    ax_res.plot(z_in, residual, color=_MODEL_COLORS["external_node_nbody"],
                lw=2.0, label="sim − EdS (should ≈ 0)")
    ax_res.plot(z_in, residual_lcdm, color=_MODEL_COLORS["lcdm"],
                lw=1.5, ls="--", label="ΛCDM − EdS (should be large)")
    ax_res.set_xscale("log")
    ax_res.set_xlabel("Redshift z", fontsize=12)
    ax_res.set_ylabel("Δμ vs EdS [mag]", fontsize=10)
    ax_res.grid(True, alpha=0.3, which="both")
    ax_res.legend(fontsize=8, loc="upper right")

    max_dev = float(np.nanmax(np.abs(residual)))
    ax_top.text(
        0.02, 0.02,
        f"max|sim−EdS| = {max_dev:.3f} mag\n"
        f"(EdS-ΛCDM gap ≈ {float(np.nanmax(np.abs(residual_lcdm))):.2f} mag at z_max)",
        transform=ax_top.transAxes,
        fontsize=8, color="#333333",
        verticalalignment="bottom",
    )

    _footer(ax_res, f"t_start={t_start_Gyr} Gyr, M=0 EdS validation")
    out = figure_path(workstream, name)
    fig.savefig(out, dpi=_DPI, bbox_inches=_BBOX)
    plt.close(fig)
    return out


