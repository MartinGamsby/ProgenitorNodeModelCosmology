def plot_ms_heatmap(
    df,
    metric_col: str,
    workstream: str,
    name: str,
    *,
    title: Optional[str] = None,
    colorbar_label: Optional[str] = None,
    cmap: str = "viridis_r",
    mark_best: bool = True,
    best_is_min: bool = True,
    vmin: Optional[float] = None,
    vmax: Optional[float] = None,
) -> str:
    """Plot a 2-D M-S heatmap of a scalar metric from a sweep results DataFrame.

    Reads ``M_factor`` and ``S_gpc`` columns to form the grid axes; fills cells
    with ``metric_col``. Multiple rows for the same (M, S) are averaged. The
    best cell is marked with a white star when ``mark_best=True``.

    Args:
        df:             pandas DataFrame (or object with column access) containing
                        at minimum columns ``M_factor``, ``S_gpc``, and
                        ``metric_col``.
        metric_col:     Column name to colour the heatmap (e.g. ``"chi2_dof"``).
        workstream:     Sub-directory, e.g. ``"ws1"``.
        name:           PNG filename stem.
        title:          Figure title. Defaults to ``"M-S heatmap: <metric_col>"``.
        colorbar_label: Colorbar axis label. Defaults to ``metric_col``.
        cmap:           Matplotlib colormap name.
        mark_best:      Whether to mark the best cell with a star.
        best_is_min:    True => best = minimum (chi2); False => best = maximum.
        vmin / vmax:    Colormap range clipping.

    Returns:
        Path to the saved PNG.
    """
    import pandas as _pd

    df = _pd.DataFrame(df)  # accept dicts / DataFrames uniformly

    required = {"M_factor", "S_gpc", metric_col}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(
            f"plot_ms_heatmap: DataFrame is missing columns {sorted(missing)}. "
            f"Available: {sorted(df.columns)}"
        )

    # Pivot: average metric over duplicate (M, S) pairs
    pivot = (
        df[["M_factor", "S_gpc", metric_col]]
        .astype({metric_col: float})
        .groupby(["M_factor", "S_gpc"])[metric_col]
        .mean()
        .reset_index()
        .pivot(index="S_gpc", columns="M_factor", values=metric_col)
    )

    M_vals = pivot.columns.values.astype(float)
    S_vals = pivot.index.values.astype(float)
    Z = pivot.values  # shape (n_S, n_M)

    fig, ax = plt.subplots(figsize=(9, 6))

    img = ax.pcolormesh(
        M_vals, S_vals, Z,
        cmap=cmap, shading="nearest",
        vmin=vmin, vmax=vmax,
    )
    cbar = fig.colorbar(img, ax=ax)
    cbar.set_label(colorbar_label or metric_col, fontsize=11)

    ax.set_xlabel("M (node mass factor)", fontsize=12)
    ax.set_ylabel("S (node separation, Gpc)", fontsize=12)
    ax.set_title(title or f"M-S heatmap: {metric_col}", fontsize=13)

    # Mark best cell
    if mark_best:
        flat = Z.ravel()
        finite_mask = np.isfinite(flat)
        if np.any(finite_mask):
            finite_vals = flat.copy()
            finite_vals[~finite_mask] = np.inf if best_is_min else -np.inf
            best_flat = int(np.argmin(finite_vals) if best_is_min else np.argmax(finite_vals))
            bi, bj = np.unravel_index(best_flat, Z.shape)
            ax.plot(
                M_vals[bj], S_vals[bi],
                marker="*", color="white", ms=14, zorder=10,
                markeredgecolor="black", markeredgewidth=0.7,
                label=f"best {metric_col}={Z[bi, bj]:.3f}",
            )
            ax.legend(fontsize=9, loc="upper right")

    ax.set_xscale("log") if np.ptp(np.log10(M_vals[M_vals > 0])) > 1.5 else None

    _footer(ax, f"metric={metric_col}")
    fig.tight_layout()
    out = figure_path(workstream, name)
    fig.savefig(out, dpi=_DPI, bbox_inches=_BBOX)
    plt.close(fig)
    return out


