# Convenience: regenerate all heatmaps from a CSV (--plots-only mode)
# ---------------------------------------------------------------------------

def plots_from_csv(
    csv_path: str,
    workstream: str = "ws1",
    *,
    metrics: Optional[list] = None,
) -> list[str]:
    """Regenerate all standard heatmap figures from a sweep results CSV.

    This is the core of the ``--plots-only <csv>`` mode in WS1.  It reads
    the CSV, then emits F1, F2 (if cols present), F4, and F9.

    Args:
        csv_path:    Path to the sweep CSV.
        workstream:  Sub-directory for the output figures.
        metrics:     List of metric column names to heatmap. Defaults to
                     ``["chi2_dof", "chi2_lcdm", "growth_factor"]``.

    Returns:
        List of saved PNG paths.
    """
    import pandas as _pd

    df = _pd.read_csv(csv_path)
    if metrics is None:
        metrics = []
        for col in ("chi2_dof", "chi2_lcdm", "chi2_eds"):
            if col in df.columns:
                metrics.append(col)
        if not metrics and "chi2_dof" in df.columns:
            metrics = ["chi2_dof"]

    out_paths: list[str] = []

    for m in metrics:
        if m not in df.columns:
            warnings.warn(f"plots_from_csv: column {m!r} not in CSV, skipping.")
            continue
        best_is_min = "chi2" in m or "rmse" in m or "diff" in m
        out_paths.append(plot_ms_heatmap(
            df, m, workstream,
            name=f"ms_{m}_heatmap",
            best_is_min=best_is_min,
        ))

    if "growth_factor" in df.columns:
        out_paths.append(plot_growth_map(
            df, workstream, "growth_map",
        ))

    if "anchor_ok" in df.columns:
        out_paths.append(plot_runaway_boundary(
            df, workstream, "runaway_boundary",
        ))

    return out_paths
