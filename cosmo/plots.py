# ---------------------------------------------------------------------------
# Path helper
# ---------------------------------------------------------------------------

def figure_path(workstream: str, name: str) -> str:
    """Return ``results/figures/<workstream>/<name>.png``, creating the dir.

    Args:
        workstream: Sub-directory label, e.g. ``"ws1"``, ``"ws2"``.
        name:       Descriptive filename stem (no extension, no spaces).

    Returns:
        Absolute path string ending in ``.png``.
    """
    directory = os.path.join(_RESULTS_ROOT, workstream)
    os.makedirs(directory, exist_ok=True)
    return os.path.join(directory, f"{name}.png")


# ---------------------------------------------------------------------------
# Footer helper
# ---------------------------------------------------------------------------

def _footer(ax: plt.Axes, config_str: str) -> None:
    """Stamp a tiny config + git-rev footer at the bottom of the axes."""
    try:
        rev = subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=os.path.dirname(os.path.abspath(__file__)),
            stderr=subprocess.DEVNULL,
        ).decode().strip()
    except Exception:
        rev = "unknown"
    footer_text = f"rev {rev} | {config_str}"
    ax.annotate(
        footer_text,
        xy=(0.5, 0.0), xycoords="figure fraction",
        ha="center", va="bottom",
        fontsize=5, color="#888888",
        annotation_clip=False,
    )


