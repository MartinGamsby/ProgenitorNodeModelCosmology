# F9 — Runaway-boundary map
# ---------------------------------------------------------------------------

def plot_runaway_boundary(
    df,
    workstream: str,
    name: str,
    *,
    anchor_col: str = "anchor_ok",
    title: str = "Runaway boundary in (M, S) — red = runaway, green = bound",
) -> str:
    """Binary (bound / runaway) map over the (M, S) grid from a sweep CSV.

    Each cell is coloured green (anchor_ok=True, bound) or red (runaway). The
    S_crit ∝ M^(1/3) scaling is drawn as an annotation guide.

    Args:
        df:          Sweep results DataFrame.
        workstream:  Sub-directory.
        name:        PNG filename stem.
        anchor_col:  Boolean column marking physical configs (default ``"anchor_ok"``).
        title:       Figure title.

    Returns:
        Path to the saved PNG.
    """
    import pandas as _pd

    df = _pd.DataFrame(df)
    required = {"M_factor", "S_gpc", anchor_col}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"plot_runaway_boundary: missing columns {sorted(missing)}.")

    df2 = df[["M_factor", "S_gpc", anchor_col]].copy()
    df2["anchor_bool"] = df2[anchor_col].map(
        lambda v: (str(v).strip().lower() not in ("false", "0", "no"))
    ).astype(int)

    pivot = (
        df2.groupby(["M_factor", "S_gpc"])["anchor_bool"]
        .mean()
        .reset_index()
        .pivot(index="S_gpc", columns="M_factor", values="anchor_bool")
    )

    M_vals = pivot.columns.values.astype(float)
    S_vals = pivot.index.values.astype(float)
    Z = pivot.values   # values in [0, 1] — fraction of runs that are bound

    fig, ax = plt.subplots(figsize=(9, 6))
    cmap_rb = mcolors.ListedColormap(["#d62728", "#2ca02c"])
    img = ax.pcolormesh(
        M_vals, S_vals, Z,
        cmap=cmap_rb, shading="nearest", vmin=0, vmax=1,
    )
    cbar = fig.colorbar(img, ax=ax, ticks=[0.25, 0.75])
    cbar.ax.set_yticklabels(["runaway", "bound"])

    # S_crit ~ M^(1/3) guide line
    if len(M_vals) > 1:
        M_range = np.linspace(M_vals.min(), M_vals.max(), 200)
        # Fit S_crit for each M using the boundary (cells that transition 0->1)
        # Simplified: draw reference line anchored at median M
        m_mid = M_vals[len(M_vals) // 2]
        # Find the lowest S that is bound at m_mid (if available)
        try:
            col_idx = int(np.argmin(np.abs(M_vals - m_mid)))
            col_vals = Z[:, col_idx]
            bound_rows = np.where(col_vals > 0.5)[0]
            if len(bound_rows):
                s_ref = S_vals[bound_rows[0]]
                s_guide = s_ref * (M_range / m_mid) ** (1.0 / 3.0)
                ax.plot(M_range, s_guide, "k--", lw=1.5, alpha=0.6,
                        label=r"$S_{\rm crit} \propto M^{1/3}$ guide")
                ax.legend(fontsize=9)
        except Exception:
            pass

    ax.set_xlabel("M (node mass factor)", fontsize=12)
    ax.set_ylabel("S (node separation, Gpc)", fontsize=12)
    ax.set_title(title, fontsize=12)
    try:
        if np.ptp(np.log10(M_vals[M_vals > 0])) > 1.5:
            ax.set_xscale("log")
    except Exception:
        pass

    _footer(ax, f"anchor={anchor_col}")
    fig.tight_layout()
    out = figure_path(workstream, name)
    fig.savefig(out, dpi=_DPI, bbox_inches=_BBOX)
    plt.close(fig)
    return out


